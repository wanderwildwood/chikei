package com.kylecorry.trail_sense.shared.house

import java.io.File
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * The Licenses page's data as the build made it: the AboutLibraries plugin writes
 * build/generated/aboutLibraries/<variant>/res/raw/aboutlibraries.json before the unit tests
 * compile (it is part of the merged resources the R class comes from).
 */
class LicencesTest {
    private val json: File? = File("build/generated/aboutLibraries").walkTopDown()
        .filter { it.name == "aboutlibraries.json" }
        .sortedBy { if ("release" in it.path) 0 else 1 }
        .firstOrNull()

    private val generated by lazy { licenceComponentsFromJson(json!!.readText()) }

    private val data by lazy {
        LicencesData(
            "chikei", SOURCE_URL, "GPL-3.0-only", generated,
            LICENCE_RAW.map { LicenceText(it.first, it.first, it.second) }, emptyList(),
        )
    }

    /** What must be on the page whatever else changes: group:artifact, or a config/libraries name. */
    private val EXPECTED = listOf(
        // Group:artifact ids (or config/libraries names) that must be on the page.
        "com.mudita:MMD", "com.github.kylecorry31.mapsforge:mapsforge-map-android", "com.google.android.material:material",
        "com.kylecorry.andromeda:core", "com.kylecorry.andromeda:wkt", "com.kylecorry:sol", "com.kylecorry:luna",
        "org.checkerframework:checker-qual", "com.atlassian.commonmark:commonmark",
        "androidx.datastore:datastore-preferences-external-protobuf", "androidx.camera:camera-core",
        "Trail Sense", "Lato typeface", "NPMap Symbol Library", "MAD Location Manager", "pyTMD",
        "NASA World Wind (ported by Berico Technologies)", "Map data", "Survival guide",
    )

    @Test fun theBuildListedTheLibraries() {
        assertNotNull("no generated aboutlibraries.json: is the AboutLibraries plugin applied?", json)
        assertTrue(generated.size >= 5)
    }

    @Test fun theDataHasNoProblems() {
        assertEquals(emptyList<String>(), licencesProblems(data))
    }

    @Test fun everyExpectedComponentIsListed() {
        val missing = EXPECTED.filterNot { id -> generated.any { it.note?.startsWith("$id ") == true || it.name == id } }
        assertEquals(emptyList<String>(), missing)
    }

    /** MIT and BSD need the library's own copyright line: each carries its own text, never the bare family text. */
    @Test fun everyMitAndBsdLibraryCarriesItsOwnText() {
        val bare = generated.filter { c ->
            c.licence.split(", ").any { it.startsWith("MIT") || it.startsWith("BSD") } && c.texts.none { t ->
                t.title.contains("MIT") || t.title.contains("BSD")
            }
        }.map { it.note ?: it.name }
        assertEquals(emptyList<String>(), bare)
    }

    /** Only what the release APK carries: no debug-only or test-only artifact. */
    @Test fun noDebugOnlyArtifactIsListed() {
        assertTrue("release list not generated", json!!.path.contains("release"))
        val debugOnly = listOf("androidx.fragment:fragment-testing-manifest", "androidx.compose.ui:ui-tooling", "androidx.compose.ui:ui-test-manifest")
        assertEquals(emptyList<String>(), debugOnly.filter { id -> generated.any { it.note?.startsWith("$id ") == true } })
    }

    @Test fun theSourceLinkIsTheRepo() {
        assertEquals("https://github.com/wanderwildwood/chikei", SOURCE_URL)
    }

    @Test fun gplIsFirstAndEveryTextIsBundled() {
        assertEquals("gpl", orderedTexts(data.texts).first().id)
        val raw = File("src/main/res/raw")
        assertTrue(raw.listFiles().orEmpty().count { it.extension == "txt" } >= LICENCE_RAW.size)
        assertTrue(licenceParagraphs(File(raw, raw.list().orEmpty().first { it.contains("gpl") }).readText()).size > 10)
    }
}
